// packages/shared/course/<level>/vocab.js and examples.js.
//
// A level is published as far as it is finished: its lessons are taken in order up to the first one with a
// word still missing its Uzbek meaning. Everything after that stays in the plan until the translation
// catches up, so the app never shows a card with half its content. Rerun after editing vocab/uz.tsv or
// vocab/examples.tsv (npm run build:course); the output is deterministic.
