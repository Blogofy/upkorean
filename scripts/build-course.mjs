function readTsv(file) {
  if (!fs.existsSync(file)) return [];
  const lines = fs.readFileSync(file, "utf8").split(/\r?\n/).filter((line) => line && !line.startsWith("#"));
  const head = lines.shift().split("\t");
  return lines.map((line) => Object.fromEntries(line.split("\t").map((cell, i) => [head[i], cell])));
}

const plan = readTsv(PLAN);
const examples = new Map(readTsv(EXAMPLES).map((row) => [row.key, row]));
const unknownThemes = new Set();
const report = [];

for (const level of [...new Set(plan.map((row) => row.level))]) {
  const lessons = [];
  for (const row of plan.filter((r) => r.level === level)) {
    const n = Number(row.block);
    (lessons[n - 1] ||= []).push(row);
  }
  const ready = [];
  for (const rows of lessons) {
    if (rows.some((row) => !row.uz.trim())) break;
    ready.push(rows);
  }

  const dir = path.join(COURSE, level);
  const files = ["vocab.js", "examples.js"].map((name) => path.join(dir, name));
  if (!ready.length) {
    // Nothing finished yet: no folder, and the server announces the level as locked.
    for (const file of files) fs.rmSync(file, { force: true });
    if (fs.existsSync(dir) && !fs.readdirSync(dir).length) fs.rmdirSync(dir);
    report.push(`${level}: 0 / ${lessons.length} qism (yopiq)`);
    continue;
  }

  const vocabLines = ready.map((rows) => {
    const theme = rows[0].block_theme;
    if (theme && !THEMES[theme]) unknownThemes.add(theme);
    const lesson = {
      g: Math.min(...rows.map((row) => Number(row.grade.replace("급", "")))),
      t: THEMES[theme] || "",
      w: rows.map((row) => [Number(row.nid), row.word, row.uz.trim()]),
    };
    return `  ${JSON.stringify(lesson)},`;
  });

  const exampleLines = [];
  for (const rows of ready) {
    for (const row of rows) {
      const example = examples.get(row.key);
      if (!example || !example.ko) continue;
      const entry = { id: Number(row.nid), w: row.word, ko: example.ko, hl: example.hl, uz: example.uz };
      if (example.cloze) entry.cloze = example.cloze;
      if (example.note) entry.note = example.note;
      exampleLines.push(`  ${JSON.stringify(entry)},`);
    }
  }

  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(files[0], [
    "// Generated by scripts/build-course.mjs from vocab/plan.tsv — edit vocab/uz.tsv and rerun, not this file.",
    "// One part (ten words, one sitting) per entry, in the order they are taught; a day's lesson is read off it.",
    "// g — the lowest NIKL grade in it (1–6), t — its theme in Uzbek (\"\" when it has none), w — its words as",
    "// [nid, korean, uzbek], nid being the word's number in the NIKL graded list.",
    "export default [",
    ...vocabLines,
    "];",
    "",
  ].join("\n"));
  fs.writeFileSync(files[1], [
    "// Generated by scripts/build-course.mjs from vocab/examples.tsv — edit that file and rerun, not this one.",
    "// id — the word's nid; w — the word; ko — the sentence; hl — the part of ko to highlight; cloze — the part",
    "// blanked out in sentence completion; uz — the Uzbek translation, {braces} around the translated word.",
    "export default [",
    ...exampleLines,
    "];",
    "",
  ].join("\n"));
  const words = ready.reduce((sum, rows) => sum + rows.length, 0);
  report.push(`${level}: ${ready.length} / ${lessons.length} qism, ${words} so'z, ${exampleLines.length} misol`);
}

for (const line of report) console.log(line);
